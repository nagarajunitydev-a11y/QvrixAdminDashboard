CREATE OR REPLACE FUNCTION public.link_employee_to_auth_user(p_user_id uuid, p_email text, p_role text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
    -- Only process users with 'employee' role
    if p_role <> 'employee' then
        return;
    end if;

    if p_email is null then
        return;
    end if;

    -- Try to find an existing employee record with matching email and no user_id yet
    update public.employees
    set user_id = p_user_id,
        updated_at = now()
    where email = p_email
      and user_id is null;

    -- If no existing record was updated, create a basic employee record
    -- (This handles the case where the mobile app user signs up before admin creates profile)
    if not found then
        insert into public.employees (user_id, first_name, last_name, email, is_active)
        values (
            p_user_id,
            -- Extract first name from email (before @ or .)
            case
                when p_email like '%@%' then split_part(p_email, '@', 1)
                else p_email
            end,
            -- Last name defaults to empty; admin can update later
            '',
            p_email,
            true
        )
        on conflict (email) do update
        set user_id = excluded.user_id,
            updated_at = now()
        where employees.user_id is null;
    end if;
end;
$function$
;
CREATE OR REPLACE FUNCTION public.mark_stale_sessions_exited(p_timeout_minutes integer DEFAULT 15)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare updated integer; cutoff bigint;
begin
  if coalesce(auth.role(), '') <> 'service_role' and public.get_user_role() is distinct from 'manager' then
    raise insufficient_privilege using message = 'Manager access is required';
  end if;
  if p_timeout_minutes is null or p_timeout_minutes <= 0 or p_timeout_minutes > 1440 then
    raise invalid_parameter_value using message = 'Timeout must be between 1 and 1440 minutes';
  end if;
  cutoff := extract(epoch from now()) * 1000 - (p_timeout_minutes::bigint * 60000);
  update public.presence_sessions
  set exit_timestamp = greatest(entry_timestamp, cutoff),
      total_hours = (greatest(entry_timestamp, cutoff) - entry_timestamp) / 3600000.0,
      is_synced = false
  where exit_timestamp is null and entry_timestamp <= cutoff
    and (last_heartbeat is null or last_heartbeat < cutoff);
  get diagnostics updated = row_count;
  return updated;
end;
$function$
;
CREATE OR REPLACE FUNCTION public.update_session_heartbeats()
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare updated integer;
begin
  if coalesce(auth.role(), '') <> 'service_role' and public.get_user_role() is distinct from 'manager' then
    raise insufficient_privilege using message = 'Manager access is required';
  end if;
  update public.presence_sessions ps set last_heartbeat = logs.timestamp
  from (
    select user_id, site_id, max(timestamp) as timestamp from public.location_logs
    where timestamp > extract(epoch from now()) * 1000 - 3600000
    group by user_id, site_id
  ) logs
  where ps.user_id=logs.user_id and ps.site_id=logs.site_id and ps.exit_timestamp is null
    and (ps.last_heartbeat is null or ps.last_heartbeat < logs.timestamp);
  get diagnostics updated = row_count;
  return updated;
end;
$function$
;
