CREATE OR REPLACE FUNCTION public.handle_auth_user_change()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if new.raw_app_meta_data->>'role' = 'employee' and new.email_confirmed_at is not null then
    perform public.link_employee_to_auth_user(new.id, new.email, 'employee');
  end if;
  return new;
end;
$function$
